interface Annotation { readings: Map<string, Set<string>>; pinyin: boolean }

function ChoiceQuestion({ exercise, attempt, submit, next, busy, readings, pinyin, speak }: Annotation & { speak: boolean; exercise: ChoiceExercise; attempt?: ExerciseAttempt; submit: (response: unknown) => void; next: () => void; busy: boolean }) {
  const [selected, setSelected] = useState(attempt ? Number(attempt.response) : -1)
  const chineseQuestion = exercise.direction === 'zh-to-en'
  const speechId = useId()
  useEffect(() => () => { if (getPlaybackState().activeId === speechId) stopBrowserSpeech() }, [speechId])
  const choose = (index: number) => {
    setSelected(index)
    if (!speak || chineseQuestion) return
    try { playBrowserSpeech(speechId, exercise.options[index], 'zh-Hans') } catch (reason) { console.error('Choice speech failed.', reason) }
  }
  return <>
    {chineseQuestion
      ? <p className="practice-prompt native"><AnnotatedChinese text={exercise.question} readings={readings} pinyin={pinyin} /></p>
      : <p className="practice-prompt" lang="en">{exercise.question}</p>}
    <fieldset className="answer-options" disabled={busy || Boolean(attempt)}><legend className="visually-hidden">Choose an answer</legend>
      {exercise.options.map((option, index) => <label key={index} className={`answer-option ${selected === index ? 'selected' : ''} ${attempt && index === exercise.answer ? 'correct-option' : ''}`}>
        <input type="radio" name="answer" value={index} checked={selected === index} onChange={() => choose(index)} />
        {chineseQuestion ? <span lang="en">{option}</span> : <span><AnnotatedChinese text={option} readings={readings} pinyin={pinyin} /></span>}
        {!chineseQuestion && <HearButton text={option} locale="zh-Hans" label={`Hear option ${index + 1}`} iconOnly />}
        <span className="answer-option-mark">{attempt && index === exercise.answer && <CheckCircle2 size={18} aria-label="Correct answer" />}</span>
      </label>)}
    </fieldset>
    <AnswerButton result={attempt?.correct} busy={busy} ready={selected >= 0} onCheck={() => submit(selected)} onNext={next} />
  </>
}

function TilesQuestion({ exercise, attempt, submit, next, busy, readings, pinyin, speak }: Annotation & { speak: boolean; exercise: TilesExercise; attempt?: ExerciseAttempt; submit: (response: unknown) => void; next: () => void; busy: boolean }) {
  const all = [...exercise.tiles, ...exercise.distractors]
  const [placed, setPlaced] = useState<number[]>(() => {
    if (!attempt) return []
    const answer = JSON.parse(attempt.response) as string[]
    const used = new Set<number>()
    return answer.map(text => {
      const index = exercise.shuffled.find(candidate => !used.has(candidate) && all[candidate] === text)
      if (index !== undefined) used.add(index)
      return index ?? -1
    }).filter(index => index >= 0)
  })
  const locked = busy || Boolean(attempt)
  const speechId = useId()
  useEffect(() => () => { if (getPlaybackState().activeId === speechId) stopBrowserSpeech() }, [speechId])
  const say = (index: number) => {
    if (!speak) return
    try { playBrowserSpeech(speechId, all[index], 'zh-Hans') } catch (reason) { console.error('Tile speech failed.', reason) }
  }
  return <>
    <p className="practice-prompt" lang="en">{exercise.translation}</p>
    <div className="tile-answer" lang="zh-Hans" role="group" aria-label="Your sentence">
      {placed.length ? placed.map(index => <button key={index} type="button" className="tile" disabled={locked} onClick={() => { setPlaced(placed.filter(item => item !== index)); say(index) }}><AnnotatedChinese text={all[index]} readings={readings} pinyin={pinyin} /></button>)
        : <span className="small muted">Tap the tiles in order to build the sentence.</span>}
    </div>
    <div className="tile-bank" lang="zh-Hans" role="group" aria-label="Available tiles">
      {exercise.shuffled.map(index => <button key={index} type="button" className={`tile ${placed.includes(index) ? 'tile-used' : ''}`} disabled={locked || placed.includes(index)} onClick={() => { setPlaced([...placed, index]); say(index) }}><AnnotatedChinese text={all[index]} readings={readings} pinyin={pinyin} /></button>)}
    </div>
    <AnswerButton result={attempt?.correct} busy={busy} ready={placed.length >= 2} onCheck={() => submit(placed.map(index => all[index]))} onNext={next} />
  </>
}

interface MatchCell { ref: string; text: string; side: 'left' | 'right' }

/** Tap one cell, then one in the other column. A right pair locks; a wrong one is a miss charged to the first cell tapped, and the lesson goes on. */
function MatchQuestion({ exercise, attempt, submit, next, busy, readings, pinyin, speak, chinese }: Annotation & { speak: boolean; exercise: MatchExercise; attempt?: ExerciseAttempt; submit: (response: unknown) => void; next: () => void; busy: boolean; chinese: (ref: string) => string }) {
  const [locked, setLocked] = useState<string[]>(() => attempt ? exercise.pairs.map(pair => pair.ref) : [])
  const [selected, setSelected] = useState<MatchCell>()
  const [wrong, setWrong] = useState<[string, string]>()
  const [misses, setMisses] = useState<string[]>([])
  const speechId = useId()
  useEffect(() => () => { if (getPlaybackState().activeId === speechId) stopBrowserSpeech() }, [speechId])
  const [leftSide, rightSide] = matchSides(exercise.mode)
  const left: MatchCell[] = exercise.pairs.map(pair => ({ ref: pair.ref, text: pair.left, side: 'left' }))
  const right: MatchCell[] = exercise.order.map(index => ({ ref: exercise.pairs[index].ref, text: exercise.pairs[index].right, side: 'right' }))
  const sideOf = (cell: MatchCell) => cell.side === 'left' ? leftSide : rightSide
  const done = locked.length === exercise.pairs.length
  const tap = (cell: MatchCell) => {
    if (busy || attempt || locked.includes(cell.ref)) return
    setWrong(undefined)
    if (speak && sideOf(cell) !== 'en') {
      try { playBrowserSpeech(speechId, sideOf(cell) === 'zh' ? cell.text : chinese(cell.ref), 'zh-Hans') } catch (reason) { console.error('Match speech failed.', reason) }
    }
    if (!selected || selected.side === cell.side) { setSelected(cell); return }
    if (selected.ref === cell.ref) { setLocked([...locked, cell.ref]); setSelected(undefined); return }
    setMisses([...misses, selected.ref])
    setWrong([selected.ref + ':' + selected.side, cell.ref + ':' + cell.side])
    setSelected(undefined)
  }
  const cellView = (cell: MatchCell) => {
    const key = cell.ref + ':' + cell.side
    const state = locked.includes(cell.ref) ? 'match-locked' : wrong?.includes(key) ? 'match-wrong' : selected && selected.ref === cell.ref && selected.side === cell.side ? 'match-selected' : ''
    const side = sideOf(cell)
    return <button key={key} type="button" className={`tile match-cell ${state}`} aria-pressed={state === 'match-selected'} disabled={busy || Boolean(attempt) || locked.includes(cell.ref)}
      lang={side === 'en' ? 'en' : side === 'zh' ? 'zh-Hans' : undefined} onClick={() => tap(cell)}>
      {side === 'zh' ? <AnnotatedChinese text={cell.text} readings={readings} pinyin={pinyin} /> : cell.text}{locked.includes(cell.ref) && <CheckCircle2 size={14} aria-label="Matched" />}
    </button>
  }
  return <>
    <p className="practice-prompt" lang="en">Match each pair: tap one, then its partner.</p>
    <div className="match-board" role="group" aria-label="Pairs to match">
      <div className="match-column" role="group" aria-label="First column">{left.map(cellView)}</div>
      <div className="match-column" role="group" aria-label="Second column">{right.map(cellView)}</div>
    </div>
    {wrong && <p className="small muted match-hint" role="status">Not a pair. Try again.</p>}
    <AnswerButton result={attempt?.correct} busy={busy} ready={done} onCheck={() => submit(misses)} onNext={next} />
  </>
}

/** A collection lesson opens like a lesson: the words (new ones in full, known ones compact), then the grammar, then the line itself. */
function CollectionIntroduction({ catalog, session, workspace, run, busy, now, begin }: PageProps & { catalog: Catalog; session: ExerciseSession; begin: () => void }) {
  const known = new Set(workspace.knowledge.map(entry => entry.ref))
  const cardOf = (ref: string) => workspace.studyCards.find(card => card.id === cardId(ref, DOMAIN))
  const wellKnown = (ref: string) => known.has(ref) || cardOf(ref)?.state === 'review'
  const units = unitsOf(catalog, session.targetRefs)
  const words = units.filter(unit => unit.kind === 'vocabulary'), grammar = units.filter(unit => unit.kind === 'grammar')
  const newWords = words.filter(unit => !wellKnown(unit.ref)), knownWords = words.filter(unit => wellKnown(unit.ref))
  const lines = session.targetRefs.filter(isPhraseRef)
  const card = (unit: Unit, compact = false) => <UnitCard key={unit.ref} catalog={catalog} unit={unit} card={cardOf(unit.ref)} pinyin={workspace.preferences.pinyin} now={now} run={run} busy={busy}
    route={`lessons/session/${session.id}`} hideStatus compact={compact} />
  return <>
    <a href="#lessons" className="back-link"><ArrowLeft size={16} /> Lessons</a>
    <PageHeading eyebrow="COLLECTION LESSON" title="Learn the line.">Words first, then grammar, then the line itself.</PageHeading>
    <ol className="small muted phase-steps" aria-label="Lesson order">{(session.phases ?? []).map(phase => <li key={phase.kind}>{PHASE_LABEL[phase.kind]}</li>)}</ol>
    {words.length === 0 && <p className="notice" role="status">This line has no vocabulary from the curriculum, so you go straight to the line.</p>}
    {words.length > 0 && <section aria-label="Words"><h2>Words</h2>
      {newWords.length > 0 && <div className="word-grid">{newWords.map(unit => card(unit))}</div>}
      {knownWords.length > 0 && <><p className="small muted">You know these</p><div className="word-grid">{knownWords.map(unit => card(unit, true))}</div></>}</section>}
    {grammar.length > 0 && <section aria-label="Grammar"><h2>Grammar</h2><div className="word-grid">{grammar.map(unit => card(unit))}</div></section>}
    {lines.length > 0 && <section aria-label="The line"><h2>The line</h2><p className="small muted">Once the parts are known, you will work with the line itself.</p></section>}
    <StartFooter session={session} run={run} busy={busy} begin={begin} />
  </>
}

/** The always-visible bottom bar of a lesson's introduction: disabled while the AI writes the exercises, Try again if that failed or was interrupted, Start when ready. */
function StartFooter({ session, run, busy, begin }: Pick<PageProps, 'run' | 'busy'> & { session: ExerciseSession; begin: () => void }) {
  const ready = session.exercises.length > 0
  const running = !ready && session.generation === 'running' && isGenerating(session.id)
  const parts = Math.max(1, session.phases?.length ?? 1)
  const count = session.exerciseCount
  return <div className="start-panel" role="region" aria-label="Start the exercises">
    {ready && <p className="small muted">{session.generation === 'running' ? `${session.exercises.length} exercises ready, more coming. You can start now.` : `${session.exercises.length} exercises in ${parts} ${parts === 1 ? 'part' : 'parts'}. You can start without reading every card.`}</p>}
    {running && <p className="small muted" role="status">Your AI model is writing {count ? `${count} exercises` : 'the exercises'}. The cards above are ready to read.</p>}
    {!ready && !running && <p className="small error-text" role="alert">{session.generation === 'failed' && session.generationError ? session.generationError : 'The exercises were not finished, for example because the page was reloaded while they were being written.'}</p>}
    {ready || running
      ? <div className="button-row"><button className="button secondary" disabled={busy} onClick={() => { if (window.confirm('Discard this unfinished lesson? Answers you already gave stay recorded.')) void run(() => discardSession(session.id)) }}>Discard</button>
        <button className="button primary" disabled={busy || running} onClick={begin}>{running ? 'Generating with AI…' : <>Start <ArrowRight size={16} /></>}</button></div>
      : <div className="button-row"><button className="button secondary" disabled={busy} onClick={() => void run(() => discardSession(session.id))}>Discard</button>
        <button className="button primary" disabled={busy} onClick={() => void run(() => retryGeneration(session.id))}>Try again <RotateCcw size={16} /></button></div>}
  </div>
}

function SessionIntroduction({ catalog, session, workspace, run, busy, now, begin }: PageProps & { catalog: Catalog; session: ExerciseSession; begin: () => void }) {
  if (session.collectionId) return <CollectionIntroduction catalog={catalog} session={session} workspace={workspace} run={run} busy={busy} now={now} begin={begin} />
  const group = session.groupId ? catalog.groups.get(session.groupId) : undefined
  const units = unitsOf(catalog, session.targetRefs)
  const examplesFor = (ref: string) => (group?.group.examples ?? []).filter(example => example.segments.some(segment => `vocabulary:${segment.word}` === ref) || example.grammar.some(label => `grammar:${label}` === ref))
  return <>
    <a href="#lessons" className="back-link"><ArrowLeft size={16} /> Lessons</a>
    <PageHeading eyebrow={session.mode === 'new' ? `NEW ITEMS / HSK ${units[0]?.band ?? ''}` : 'REVIEW'} title={session.mode === 'new' ? 'Meet your new items.' : 'Items in this review.'}>
      {session.mode === 'new' ? 'Read each item and its examples, then try the exercises. Items you saw in recent sessions are mixed in.' : 'These items are due according to your review schedule.'}
    </PageHeading>
    <div className="word-grid">{units.map(unit => <UnitCard key={unit.ref} catalog={catalog} unit={unit} card={workspace.studyCards.find(card => card.id === cardId(unit.ref, DOMAIN))}
      pinyin={workspace.preferences.pinyin} now={now} examples={examplesFor(unit.ref)} run={run} busy={busy} route={`lessons/session/${session.id}`} hideStatus />)}</div>
    <StartFooter session={session} run={run} busy={busy} begin={begin} />
  </>
}

function ExercisePlayer({ catalog, session, attempt: persistedAttempt, workspace, run, busy, readings, pinyin, setPinyin }: PageProps & Annotation & {
  catalog: Catalog; session: ExerciseSession; attempt?: ExerciseAttempt; setPinyin: (value: boolean) => void
}) {
  const item = playItem(session, session.cursor)!
  const exercise: Exercise = item.exercise
  const redo = item.redo > 0
  const toRedo = redosRemaining(session)
  const phase = phaseAt(session.phases, item.index)
  const title = useRef<HTMLHeadingElement>(null)
  const pending = useRef(false)
  const tileSpeech = workspace.preferences.tileAutoSpeak !== false
  const hasPrompt = exercise.type === 'choice' && exercise.direction === 'zh-to-en'
  const promptSpeech = workspace.preferences.promptAutoPlay === true
  const promptSpeechRef = useRef(promptSpeech)
  promptSpeechRef.current = promptSpeech
  const promptId = useId()
  const entryKey = `${session.id}:${session.cursor}`
  const alreadyAnswered = Boolean(persistedAttempt)
  const answeredRef = useRef(alreadyAnswered)
  answeredRef.current = alreadyAnswered
  // Once per entry into an exercise: not on re-renders, preference changes or Check.
  useEffect(() => {
    if (!hasPrompt) return
    if (promptSpeechRef.current && !answeredRef.current) {
      try { playBrowserSpeech(promptId, (exercise as ChoiceExercise).question, 'zh-Hans') } catch (reason) { console.error('Prompt speech failed.', reason) }
    }
    return () => { if (getPlaybackState().activeId === promptId) stopBrowserSpeech() }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [entryKey, hasPrompt, promptId])
  const [savedAttempt, setSavedAttempt] = useState<ExerciseAttempt>()
  const attempt = persistedAttempt ?? savedAttempt
  useEffect(() => { title.current?.focus() }, [])
  const next = (response?: unknown) => {
    if (busy || pending.current) return
    pending.current = true
    void run(async () => {
      try {
        if (attempt) {
          await timeSave('next', () => advanceExercise(session.id, session.cursor))
        } else {
          const saved = await timeSave('check', () => submitExerciseAnswer(session.id, session.cursor, response))
          // Retain the result while the live workspace query catches up.
          setSavedAttempt(saved)
        }
      } finally {
        pending.current = false
      }
    })
  }
  const correctSentence = exercise.type === 'tiles' ? exercise.tiles.join('') : exercise.type === 'match' ? exercise.pairs.map(pair => `${pair.left} = ${pair.right}`).join('; ') : exercise.options[exercise.answer]
  const alternative = Boolean(attempt?.correct && exercise.type === 'tiles' && matchTiles(exercise, JSON.parse(attempt.response) as string[]) === 'alternative')
  const practised = [...new Set(exercise.targets.map(ref => { const unit = catalog.units.get(ref); return !unit ? 'phrase' : unit.kind === 'vocabulary' ? unit.record.ch : unit.record.pt }))].join(' / ')
  const total = queueLength(session)
  const chineseAnswer = exercise.type === 'tiles' || (exercise.type === 'choice' && exercise.direction === 'en-to-zh')
  const running = session.generation === 'running'
  const [noticeShown, setNoticeShown] = useState(true)
  return <div className="practice-player answer-player panel" data-assistant-protected={!attempt ? 'true' : undefined}>
    <div className="card-topline"><span className="eyebrow">{phase ? `${PHASE_LABEL[phase.kind].toUpperCase()} (${phase.number + 1}/${session.phases!.length})` : session.mode === 'new' ? 'NEW ITEMS' : 'REVIEW'} / {exercise.type === 'choice' ? 'CHOOSE' : exercise.type === 'match' ? 'MATCH' : 'BUILD THE SENTENCE'}</span>
      <span className="small muted">{redo && <span className="badge redo-badge">Redo</span>} {running ? `${session.cursor + (attempt ? 1 : 0)} done · more coming` : `Exercise ${session.cursor + 1} of ${total}`}{!running && toRedo > 0 && ` · ${toRedo} to redo`}</span></div>
    {session.aiNotice && noticeShown && <p className="notice small ai-notice" role="status">{session.aiNotice} <button type="button" className="text-link" onClick={() => { setNoticeShown(false); void dismissAiNotice(session.id) }}>Dismiss</button></p>}
    {running ? <progress aria-label="Session progress" /> : <progress aria-label="Session progress" value={session.cursor} max={total} />}
    <div className="practice-question-content">
      <h2 ref={title} tabIndex={-1}>{exercise.type === 'choice' ? exercise.direction === 'zh-to-en' ? 'What does this mean?' : 'Which Mandarin matches?' : exercise.type === 'match' ? 'Match the pairs.' : 'Arrange the tiles to translate this.'}</h2>
      <div className="button-row practice-tools">
        <button type="button" className="button secondary snippet-button" aria-pressed={pinyin} onClick={() => setPinyin(!pinyin)}>{pinyin ? 'Hide pinyin' : 'Show pinyin'}</button>
        {(exercise.type === 'tiles' || (exercise.type === 'match' && exercise.mode !== 'py-en')) && <button type="button" className="button secondary snippet-button" aria-pressed={tileSpeech} disabled={busy}
          onClick={() => { if (tileSpeech) stopBrowserSpeech(); void run(() => savePreferences({ tileAutoSpeak: !tileSpeech })) }}>{tileSpeech ? 'Mute tiles' : 'Speak tiles'}</button>}
        {hasPrompt && <button type="button" className="button secondary snippet-button" aria-pressed={promptSpeech} disabled={busy}
          onClick={() => { if (promptSpeech) stopBrowserSpeech(); void run(() => savePreferences({ promptAutoPlay: !promptSpeech })) }}>{promptSpeech ? 'Auto-play' : 'Auto-play off'}</button>}
        {exercise.type === 'choice' && exercise.direction === 'en-to-zh' && <button type="button" className="button secondary snippet-button" aria-pressed={tileSpeech} disabled={busy}
          onClick={() => { if (tileSpeech) stopBrowserSpeech(); void run(() => savePreferences({ tileAutoSpeak: !tileSpeech })) }}>{tileSpeech ? 'Mute choices' : 'Speak choices'}</button>}
        {hasPrompt && <HearButton text={exercise.question} locale="zh-Hans" label="Hear the Chinese" />}
      </div>
    </div>
    {exercise.type === 'match'
      ? <MatchQuestion key={`${session.id}:${session.cursor}`} exercise={exercise} attempt={attempt} submit={next} next={() => next()} busy={busy} readings={readings} pinyin={pinyin} speak={tileSpeech}
        chinese={ref => { const unit = catalog.units.get(ref); return unit?.kind === 'vocabulary' ? unit.record.ch : '' }} />
      : exercise.type === 'choice'
      ? <ChoiceQuestion key={`${session.id}:${session.cursor}`} exercise={exercise} attempt={attempt} submit={next} next={() => next()} busy={busy} readings={readings} pinyin={pinyin} speak={tileSpeech} />
      : <TilesQuestion key={`${session.id}:${session.cursor}`} exercise={exercise} attempt={attempt} submit={next} next={() => next()} busy={busy} readings={readings} pinyin={pinyin} speak={tileSpeech} />}
    {attempt && <div className={`notice answer-feedback${attempt.correct ? ' success' : ''}`} role="status">
      <strong>{attempt.correct ? 'Correct.' : 'Not quite.'}</strong>
      {alternative && <p className="small">That is another good way to say it.</p>}
      {chineseAnswer ? <p>{alternative && 'Also: '}<AnnotatedChinese text={correctSentence} readings={readings} pinyin={pinyin} /></p> : <p lang="en">{correctSentence}</p>}
      <p className="small">{exercise.explanation}</p>
      <p className="small muted practice-feedback-practised">Practiced: {practised}</p>
      <p className="small practice-feedback-detail">{redo ? (attempt.correct ? 'Redo done. It is not scored again.' : item.redo < MAX_REDOS_PER_EXERCISE ? 'Not scored again. It comes back once more at the end.' : 'Not scored again. That was the last redo.')
        : attempt.correct ? 'Saved to your reading progress.' : 'Saved. This one comes back at the end for a redo, and the item returns in later reviews.'}</p>
      <SnippetActions source={{ text: correctSentence, meaning: exercise.type === 'tiles' ? exercise.translation : exercise.explanation, locale: chineseAnswer ? 'zh-Hans' : 'en-US', title: 'Exercise answer explanation', route: `lessons/session/${session.id}` }} />
    </div>}
    <p className="small muted practice-save-note">Check answer saves your response immediately in {workspace.preferences.name}. Review the result, then use Next. You can leave and resume this exercise.</p>
  </div>
}

export function RedoPanel({ sessionId, run, busy }: Pick<PageProps, 'run' | 'busy'> & { sessionId: string }) {
  const connection = useAIConnection()
  const [generating, setGenerating] = useState(false)
  const redo = () => {
    setGenerating(true)
    void run(async () => {
      try { navigate(`lessons/session/${await startRedoSession(sessionId)}`) } finally { setGenerating(false) }
    })
  }
  return <div className="start-panel" role="region" aria-label="Redo the exercises">
    {connection === null ? <p className="small muted">Exercises are generated by your own AI connection. <a className="text-link" href="#settings">Connect a model in Settings</a> before redoing.</p>
      : <p className="small muted">{generating ? 'Your AI model is writing fresh exercises. This can take up to a minute.' : 'Redo starts a new session with fresh exercises for these items.'}</p>}
    <div className="button-row"><button className="button primary" disabled={busy || generating || !connection} onClick={redo}>Redo exercises <RotateCcw size={16} /></button>
      <a className="button secondary" href="#lessons">Back to Lessons</a></div>
  </div>
}

/** The curriculum units among refs; a collection's free phrases have no unit and are left out. */
function unitsOf(catalog: Catalog, refs: string[]): Unit[] {
  return refs.flatMap(ref => catalog.units.get(ref) ?? [])
}

export function StudySessionPage(props: PageProps & { session: ExerciseSession }) {
  const { workspace, session, run, busy } = props
  const { catalog, error } = useCatalog()
  const [started, setStarted] = useState(false)
  const [pinyin, setPinyin] = useState(false)
  const stalled = session.status === 'active' && session.generation === 'running' && session.exercises.length > 0 && !isGenerating(session.id)
  // After a reload the "running" flag has no request behind it: carry on with programmatic exercises.
  useEffect(() => { if (stalled) void settleInterrupted(session.id) }, [stalled, session.id])
  const allAttempts = workspace.exerciseAttempts.filter(attempt => attempt.sessionId === session.id)
  // The score counts first tries only; redo answers do not change it.
  const attempts = allAttempts.filter(attempt => !attempt.redo)
  if (error) return <div className="notice error" role="alert"><p>The curriculum could not be loaded. {error}</p></div>
  if (!catalog) return <div className="opening-workspace" role="status">Loading the curriculum...</div>
  if (session.status !== 'active') {
    const correct = attempts.filter(attempt => attempt.correct).length
    const units = unitsOf(catalog, [...session.targetRefs, ...session.reviewRefs])
    const group = session.groupId ? catalog.groups.get(session.groupId) : undefined
    const examplesFor = (ref: string) => (group?.group.examples ?? []).filter(example => example.segments.some(segment => `vocabulary:${segment.word}` === ref) || example.grammar.some(label => `grammar:${label}` === ref))
    const original = session.redoOf ? workspace.exerciseSessions.find(item => item.id === session.redoOf) : undefined
    return <>
      <a href="#lessons" className="back-link"><ArrowLeft size={16} /> Lessons</a>
      <PageHeading eyebrow={session.mode === 'new' ? 'NEW ITEMS' : 'REVIEW'} title={session.mode === 'new' ? 'New items' : 'Review'}>{session.status === 'abandoned' ? 'This lesson ended early.' : 'Your finished lesson.'}</PageHeading>
      <section className="panel results-strip" aria-label="Results">
        <p><strong>{attempts.length ? `${correct} / ${session.exercises.length}` : 'no answers'}</strong>{attempts.length > 0 && ' correct'} · {units.length} {units.length === 1 ? 'item' : 'items'} · {new Date(session.completedAt ?? session.createdAt).toLocaleString()}
          {' · '}<a className="text-link" href="#dictionary/vocabulary/knowledge">See your knowledge set</a></p>
        {session.redoOf && <p className="small muted">{original ? `Redo of ${new Date(original.completedAt ?? original.createdAt).toLocaleString()}` : 'Redo of an earlier session'}</p>}
        {session.rejected.length > 0 && <details><summary>{session.rejected.length} proposed exercises were discarded</summary><ul className="small muted">{session.rejected.map((reason, index) => <li key={index}>{reason}</li>)}</ul></details>}
      </section>
      <h2>Items in this session</h2>
      <div className="word-grid">{units.map(unit => <UnitCard key={unit.ref} catalog={catalog} unit={unit} card={workspace.studyCards.find(card => card.id === cardId(unit.ref, DOMAIN))}
        pinyin={workspace.preferences.pinyin} now={props.now} examples={examplesFor(unit.ref)} run={run} busy={busy} route={`lessons/session/${session.id}`} hideStatus />)}</div>
      <RedoPanel sessionId={session.id} run={run} busy={busy} />
    </>
  }
  const attempt = allAttempts.find(item => item.index === session.cursor)
  const waiting = !playItem(session, session.cursor)
  const readings = readingIndex([...new Set([...workspace.knowledge.map(entry => entry.ref), ...session.targetRefs, ...session.reviewRefs])]
    .flatMap(ref => { const unit = catalog.units.get(ref); return unit ? [unit] : [] }))
  if (session.exercises.length === 0 || (session.cursor === 0 && !attempt && !started)) {
    return <SessionIntroduction {...props} catalog={catalog} begin={() => setStarted(true)} />
  }
  return <>
    <div className="card-topline session-topline"><a href="#lessons" className="back-link"><ArrowLeft size={16} /> Lessons</a>
      <button className="button secondary" disabled={busy} onClick={() => void run(() => discardSession(session.id))}><X size={16} /> Quit lesson</button></div>
    {waiting ? <div className="practice-player panel" role="status"><p className="small muted">{session.cursor} done · more coming</p><progress aria-label="Session progress" /><p>Your AI model is still writing the rest of this lesson. The next exercise appears here as soon as it is ready.</p></div> :
    <ExercisePlayer key={`${session.id}:${session.cursor}`} {...props} catalog={catalog} attempt={attempt} readings={readings} pinyin={pinyin} setPinyin={setPinyin} />}
    <details className="lesson-overview"><summary><Sparkles size={16} /> Items in this session</summary>
      <div className="word-grid">{unitsOf(catalog, [...session.targetRefs, ...session.reviewRefs]).map(unit => { const ref = unit.ref; return <UnitCard key={ref} catalog={catalog} unit={unit} compact
        card={workspace.studyCards.find(card => card.id === cardId(ref, DOMAIN))} pinyin={workspace.preferences.pinyin} now={props.now} run={run} busy={busy} route={`lessons/session/${session.id}`} /> })}</div>
    </details>
  </>
}
