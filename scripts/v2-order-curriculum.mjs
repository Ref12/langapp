import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { parse } from 'yaml'
import { hskBands } from './v2-grammar-vocabulary.mjs'
import { buildComponentCandidateFile } from './v2-vocabulary-components.mjs'
import { validateVocabularyComponents } from './v2-component-schema.mjs'
import { lessonComponentIntroductions } from './v2-lesson-schema.mjs'

const scriptRoot = dirname(fileURLToPath(import.meta.url))
const repositoryRoot = resolve(scriptRoot, '..')
const chineseRoot = resolve(repositoryRoot, 'curriculum', 'v2', 'chinese')
const orderNote = '# Record order: ascending lb; lesson order is generated separately.'
const commentNote = '# Comments retain original source/editorial context; they do not define sorted ranges.'

function normalizeHeader(lines) {
  const cleaned = lines.filter(line =>
    !/Ordered by (?:new )?syllabus row/i.test(line) &&
    !/Source-family order/i.test(line))
  if (!cleaned.includes(orderNote)) {
    const firstBlank = cleaned.findIndex(line => line === '')
    cleaned.splice(firstBlank < 0 ? cleaned.length : firstBlank, 0, orderNote)
  }
  if (!cleaned.includes(commentNote)) {
    cleaned.splice(cleaned.indexOf(orderNote) + 1, 0, commentNote)
  }
  return cleaned
}

function normalizeHistoricalComments(lines) {
  return lines.map(line => line
    .replace(/in original row order\./i, 'identified from their original syllabus rows.')
    .replace(/in their original syllabus-row order\./i, 'identified from their original syllabus rows.'))
}

export function splitInventory(text, path = 'inventory') {
  const lines = text.replace(/\r\n/g, '\n').split('\n')
  const firstRecord = lines.findIndex(line => line.startsWith('- '))
  if (firstRecord < 0) throw new Error(`${path}: no inventory records`)
  const header = normalizeHeader(lines.slice(0, firstRecord))
  const records = []
  let pending = []
  let current
  const finish = () => {
    if (!current) return
    const value = parse(`${current.lines.join('\n')}\n`)?.[0]
    if (!value?.lb) throw new Error(`${path}: inventory record has no lb`)
    records.push({ ...current, lb: value.lb, value })
    current = undefined
  }
  for (const line of lines.slice(firstRecord)) {
    if (line.startsWith('- ')) {
      finish()
      current = { prefix: normalizeHistoricalComments(pending), lines: [line] }
      pending = []
    } else if (current && line.startsWith('  ')) {
      current.lines.push(line)
    } else {
      finish()
      pending.push(line)
    }
  }
  finish()
  return { header, records, footer: pending }
}

export function sortInventoryText(text, path) {
  const inventory = splitInventory(text, path)
  inventory.records.sort((left, right) => left.lb === right.lb ? 0 : left.lb < right.lb ? -1 : 1)
  return [
    ...inventory.header,
    ...inventory.records.flatMap(record => [...record.prefix, ...record.lines]),
    ...inventory.footer,
  ].join('\n').replace(/\n*$/, '\n')
}

function inventoryFiles() {
  return [
    ...hskBands.flatMap(band => ['vocabulary', 'grammar'].map(kind =>
      resolve(chineseRoot, `hsk-${band}`, `${kind}.yaml`))),
    resolve(chineseRoot, 'hsk-1', 'components.yaml'),
    resolve(chineseRoot, 'hsk-1', 'component-vocabulary.yaml'),
  ]
}

function generatedLessonInventory(sequence, source, kind, sourcePath) {
  const records = new Map(splitInventory(source, sourcePath).records.map(record => [record.lb, record]))
  const selected = []
  for (const [index, lesson] of sequence.lessons.entries()) {
    const units = lesson.units.filter(unit => unit.kind === kind)
    if (units.length === 0) continue
    selected.push(`# Lesson ${String(index + 1).padStart(2, '0')}: ${lesson.id} - ${lesson.title}`)
    for (const unit of units) {
      const record = records.get(unit.ref)
      if (!record) throw new Error(`${sequence.alignment}/${lesson.id}: unknown ${kind} label ${unit.ref}`)
      selected.push(...record.lines)
    }
    selected.push('')
  }
  const total = records.size
  const count = sequence.lessons.flatMap(lesson => lesson.units).filter(unit => unit.kind === kind).length
  return [
    `# Generated by scripts\\v2-order-curriculum.mjs from lessons\\${sequence.alignment}.yaml.`,
    '# Do not edit this file; edit the canonical inventory or lesson sequence and regenerate.',
    `# Teaching order currently places ${count} of ${total} ${kind} records (${sequence.coverage} coverage).`,
    '',
    ...selected,
  ].join('\n').replace(/\n*$/, '\n')
}

export function validateComponentBindings() {
  const bandRoot = resolve(chineseRoot, 'hsk-1')
  const hsk1Vocabulary = parse(readFileSync(resolve(bandRoot, 'vocabulary.yaml'), 'utf8'))
  const componentPath = resolve(bandRoot, 'components.yaml')
  const componentVocabularyPath = resolve(bandRoot, 'component-vocabulary.yaml')
  const bindingPath = resolve(bandRoot, 'vocabulary-components.yaml')
  const lessonPath = resolve(chineseRoot, 'lessons', 'hsk-1.yaml')
  const componentVocabulary = hskBands.flatMap(band => parse(readFileSync(
    resolve(chineseRoot, `hsk-${band}`, 'vocabulary.yaml'), 'utf8')))
  componentVocabulary.push(...parse(readFileSync(componentVocabularyPath, 'utf8')))
  const result = validateVocabularyComponents(parse(readFileSync(bindingPath, 'utf8')), {
    vocabulary: hsk1Vocabulary,
    componentVocabulary,
    morphemes: parse(readFileSync(componentPath, 'utf8')),
  }, { requireComplete: true })
  const sequence = parse(readFileSync(lessonPath, 'utf8'))
  lessonComponentIntroductions(sequence, new Map(hsk1Vocabulary.map(word => [word.lb, word])), result.bindings)
  return result
}

export function buildOrderedLessonInventories() {
  const lessonPath = resolve(chineseRoot, 'lessons', 'hsk-1.yaml')
  const sequence = parse(readFileSync(lessonPath, 'utf8'))
  const bandRoot = resolve(chineseRoot, 'hsk-1')
  const vocabularyPath = resolve(bandRoot, 'vocabulary.yaml')
  const grammarPath = resolve(bandRoot, 'grammar.yaml')
  return [
    {
      path: resolve(bandRoot, 'ordered-vocabulary.yaml'),
      content: generatedLessonInventory(sequence, readFileSync(vocabularyPath, 'utf8'),
        'vocabulary', vocabularyPath),
    },
    {
      path: resolve(bandRoot, 'ordered-grammar.yaml'),
      content: generatedLessonInventory(sequence, readFileSync(grammarPath, 'utf8'),
        'grammar', grammarPath),
    },
  ]
}

export function orderCurriculum({ check = false } = {}) {
  const stale = []
  for (const path of inventoryFiles()) {
    const current = readFileSync(path, 'utf8')
    const expected = sortInventoryText(current, path)
    if (current !== expected) {
      stale.push(path)
      if (!check) writeFileSync(path, expected, 'utf8')
    }
  }
  validateComponentBindings()
  for (const output of buildOrderedLessonInventories()) {
    let current
    try {
      current = readFileSync(output.path, 'utf8')
    } catch {
      current = undefined
    }
    if (current !== output.content) {
      stale.push(output.path)
      if (!check) writeFileSync(output.path, output.content, 'utf8')
    }
  }
  const candidatePath = resolve(chineseRoot, 'hsk-1', 'component-candidates.yaml')
  const candidateContent = buildComponentCandidateFile(repositoryRoot)
  let currentCandidates
  try {
    currentCandidates = readFileSync(candidatePath, 'utf8')
  } catch {
    currentCandidates = undefined
  }
  if (currentCandidates !== candidateContent) {
    stale.push(candidatePath)
    if (!check) writeFileSync(candidatePath, candidateContent, 'utf8')
  }
  if (check && stale.length > 0) {
    throw new Error(`Run npm run curriculum:v2:order:\n${stale.map(path => `- ${path}`).join('\n')}`)
  }
  return stale
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const stale = orderCurriculum({ check: process.argv.includes('--check') })
  if (!process.argv.includes('--check')) {
    console.log(`Sorted canonical inventories and updated ${stale.length} files.`)
  }
}
