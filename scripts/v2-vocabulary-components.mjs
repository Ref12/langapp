import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { Document, parse } from 'yaml'

const han = value => [...value].filter(character => /\p{Script=Han}/u.test(character))

export function buildComponentCandidates(repositoryRoot) {
  const vocabularyPath = resolve(repositoryRoot, 'curriculum', 'v2', 'chinese', 'hsk-1', 'vocabulary.yaml')
  const words = parse(readFileSync(vocabularyPath, 'utf8'))
    .filter(word => han(word.ch).length > 1)
    .sort((left, right) => left.lb < right.lb ? -1 : left.lb > right.lb ? 1 : 0)
  /** @type {Map<string, Array<{ch: string, lb: string}>>} */
  const usages = new Map()
  for (const word of words) {
    for (const character of new Set(han(word.ch))) {
      if (!usages.has(character)) usages.set(character, [])
      usages.get(character).push({ ch: word.ch, lb: word.lb })
    }
  }
  return Object.fromEntries([...usages].sort(([left], [right]) => left < right ? -1 : left > right ? 1 : 0))
}

export function buildComponentCandidateFile(repositoryRoot, candidates = buildComponentCandidates(repositoryRoot)) {
  const document = new Document()
  for (const [character, usages] of Object.entries(candidates)) {
    document.set(character, document.createNode(usages, { flow: true }))
  }
  return [
    '# Generated by scripts\\v2-vocabulary-components.mjs from HSK 1 vocabulary.',
    '# Do not edit. Character -> words using it; ch is the whole word, lb its sense label.',
    '# Repeated characters are listed once per word sense; their positions follow from ch.',
    '# Meanings and readings stay in the vocabulary inventories, not this usage index.',
    '',
    document.toString({ lineWidth: 0 }).trimEnd(),
    '',
  ].join('\n')
}
