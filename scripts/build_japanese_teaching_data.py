def selected_entry(identifier, rows, words):
    parent, ordinal = identifier.rsplit("-s", 1)
    row = rows[parent]
    word = words[re.search(r"JMdict:(\d+)", row["source_entry"])[1]]
    sense = word["sense"][int(ordinal) - 1]
    reading = row["reading"]
    kana = next(x for x in word["kana"] if x["text"] == reading)
    forms = [x for x in word["kanji"] if compatible(kana["appliesToKanji"], x["text"])
             and compatible(sense["appliesToKanji"], x["text"])]
    if not compatible(sense["appliesToKana"], reading):
        raise ValueError(f"{identifier}: sense incompatible with reading {reading}")
    bad = {"sK", "rK", "iK", "oK"}
    usable = [x for x in forms if not bad.intersection(x["tags"])]
    if "uk" in sense["misc"] and "*" in sense["appliesToKanji"]:
        spelling = reading
    elif any(x["common"] for x in usable):
        spelling = next(x["text"] for x in usable if x["common"])
    elif any(x["text"] == row["target"] for x in usable):
        spelling = row["target"]
    elif usable:
        spelling = usable[0]["text"]
    elif "*" in sense["appliesToKanji"]:
        spelling = reading
    else:
        raise ValueError(f"{identifier}: no usable restricted spelling")
    spelling = SPELLING_CHOICES.get(identifier, spelling)
    if spelling != reading and not compatible(kana["appliesToKanji"], spelling):
        raise ValueError(f"{identifier}: incompatible spelling")
    if {"arch", "obs", "rare", "vulg", "X", "derog"}.intersection(sense["misc"]):
        raise ValueError(f"{identifier}: excluded register {sense['misc']}")
    glosses = [x["text"] for x in sense["gloss"] if x["lang"] == "eng"]
    ds = LABELS.get(identifier, glosses[0])
    if not ds or len(ds) > 64:
        raise ValueError(f"{identifier}: author a concise label for {ds!r}")
    return {"id": identifier, "ch": spelling, "pr": reading, "ds": ds}, word["id"], row


