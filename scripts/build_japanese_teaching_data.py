def build_tourist(entries, vocabulary, placements, dependencies, rows, words, spellings):
    units, forms, support = [], {}, {}
    seen_v, seen_g = set(), set()
    phrase_number = 0
    for unit_id, title, outcome, phrase_specs in TOURIST_UNITS:
        phrases, needed_v, needed_g = [], [], []
        for spec in phrase_specs:
            ch, pr, ds, vs, gs, _note = spec.split("|")
            vi = list(dict.fromkeys(expand(vs)))
            gi = list(dict.fromkeys(expand(gs, grammar=True)))
            phrase_number += 1
            phrase_id = f"ja-tourist-p{phrase_number:03}"
            segments = []
            for component in TOURIST_COMPONENTS[phrase_number]:
                if component.startswith("@"):
                    name = component[1:]
                    written, spoken, lexical, constructions, note = TOURIST_ATOMIC_FORMS[name]
                    items = list(expand(lexical))
                    grammar = list(expand(constructions, grammar=True))
                    assert len(items) <= 1 and grammar
                    assert items or len(grammar) == 1
                    form_id = f"ja-form-{name}"
                    forms[form_id] = {
                        "ch": written, "pr": spoken, "items": items, "grammar": grammar,
                        "source_id": "original-ja-practical", "note": note,
                    }
                    segments.append({
                        "ch": written, "pr": spoken, "items": items,
                        "grammar": grammar, "form_id": form_id,
                    })
                else:
                    lexical, _, constructions = component.partition("~")
                    items = list(expand(lexical))
                    assert len(items) == 1
                    entry = entries.get(items[0]) or selected_entry(items[0], rows, words)[0]
                    segments.append({
                        "ch": entry["ch"], "pr": entry["pr"], "items": items,
                        "grammar": list(expand(constructions, grammar=True)),
                    })
            segment_v = list(dict.fromkeys(i for segment in segments for i in segment["items"]))
            segment_g = list(dict.fromkeys(i for segment in segments for i in segment["grammar"]))
            assert set(segment_v) == set(vi), (phrase_id, "lexical components")
            assert set(segment_g) == set(gi), (phrase_id, "construction components")
            assert "".join(segment["ch"] for segment in segments) == ch, (phrase_id, "surface")
            assert "".join(segment["pr"] for segment in segments) == pr, (phrase_id, "reading")
            phrases.append({
                "id": phrase_id, "ch": ch, "pr": pr, "ds": ds,
                "items": segment_v, "grammar": segment_g,
                "realizations": segments,
            })
            needed_v.extend(vi)
            needed_g.extend(gi)
        ordered_g, active = [], set()

        def visit(identifier):
            if identifier in seen_g or identifier in ordered_g:
                return
            if identifier in active:
                raise ValueError(f"Cyclic tourist prerequisite: {identifier}")
            active.add(identifier)
            for dependency in dependencies.get(identifier, []):
                visit(dependency)
            needed_v.extend(placements[identifier]["anchors"])
            active.remove(identifier)
            ordered_g.append(identifier)

        for identifier in needed_g:
            visit(identifier)
        needed_v = list(dict.fromkeys(needed_v))
        for identifier in needed_v:
            if identifier not in entries:
                entry, _, row = selected_entry(identifier, rows, words)
                entries[identifier] = entry
                support[identifier] = entry["ds"]
                if entry["ch"] != row["target"]:
                    spellings[identifier] = entry["ch"]
        new_v = [i for i in needed_v if i not in seen_v]
        assert len(new_v) <= 25, (unit_id, len(new_v))
        units.append({
            "id": unit_id, "title": title, "outcome": outcome,
            "vocabulary": new_v, "grammar": ordered_g,
            "review_vocabulary": [i for i in needed_v if i in seen_v],
            "review_grammar": list(dict.fromkeys(i for i in needed_g if i in seen_g)),
            "phrases": phrases,
        })
        seen_v.update(new_v)
        seen_g.update(ordered_g)
    assert set(TOURIST_COMPONENTS) == set(range(1, phrase_number + 1))
    assert set(forms) == {f"ja-form-{name}" for name in TOURIST_ATOMIC_FORMS}
    write_yaml(ROOT / "teaching" / "tourist" / "plan.yaml", {
        "schema_version": 1, "id": "ja-tourist", "title": "Japanese for a short visit",
        "language": "japanese",
        "level_basis": "Independent situation-based route with no prerequisite core level or kana course. The first five ordered units form a self-contained quick start; source bands are provenance only.",
        "review_policy": "Start with 5-8 new senses and a useful phrase. Teach the listed local construction prerequisites, then change a detail and reduce help. Retrieve earlier items later the same day and roughly 1, 3, 7 and 14 days later, adapting to evidence. Kana readings are not audio or pitch-accent models. These original phrases do not guarantee safety, accepted payment, dietary suitability, medical accuracy, or current travel arrangements; confirm with an appropriate person.",
        "quick_start": [u["id"] for u in units[:5]], "units": units,
    })
    write_yaml(OUT / "forms.yaml", forms)
    write_yaml(OUT / "support.yaml", support)
    write_yaml(OUT / "spellings.yaml", spellings)


