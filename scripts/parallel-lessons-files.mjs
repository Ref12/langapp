// Parallel Japanese and Korean lessons as files, shared by scripts/build-parallel-lessons.mjs (the pipeline) and scripts/generate-app-parallel.mjs (the app JSON).
//
// For each Chinese lesson N (the v2 groups of src/data/v2/hsk-1.generated.json: 87 for HSK 1, the lessons the learner follows) there is a Japanese and a Korean lesson N. Per language:
//   curriculum/<language>/parallel/entries.yaml      words and grammar points that the imported references (JLPT, TOPIK) do not have: source: parallel-authored
//   curriculum/<language>/parallel/zh-lessons.yaml   one record per Chinese lesson: words (entry ids), grammar taught, phrases (tokens carry entry ids)
// The imported reference files are read, never edited. Everything here is plain functions over plain data so tests can use temporary folders.
import { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { Document, isPair, parse, visit } from 'yaml'
import { createForms } from '../src/core/forms/engine.mjs'
import { analysePhrases, classifyEntries, rawVocabulary } from '../src/core/forms/retag.mjs'
import { loadClassOverrides, loadFormsRules } from './forms-data.mjs'

export const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
export const FILE_VERSION = 1
export const PARALLEL_SOURCE = 'parallel-authored'

export const LANGUAGES = {
  ja: { code: 'ja', dir: 'japanese', name: 'Japanese', prefix: 'ja-par', script: /[\p{Script=Hiragana}\p{Script=Katakana}\p{Script=Han}]/u, jlpt: ['n5', 'n4', 'n3', 'n2', 'n1'], style: 'polite です/ます style' },
  ko: { code: 'ko', dir: 'korean', name: 'Korean', prefix: 'ko-par', script: /[\p{Script=Hangul}]/u, jlpt: ['1', '2', '3', '4', '5', '6'], style: '해요체 (polite informal)' },
}
export const languageOf = code => { const language = LANGUAGES[code]; if (!language) throw new Error('--language takes ja, ko or both: ' + code); return language }

export const parallelDir = (code, base = root) => join(base, 'curriculum', languageOf(code).dir, 'parallel')
export const entriesFile = (code, base = root) => join(parallelDir(code, base), 'entries.yaml')
export const lessonsFile = (code, base = root) => join(parallelDir(code, base), 'zh-lessons.yaml')
export const reportFile = (code, base = root) => join(parallelDir(code, base), 'report.yaml')
export const appJsonFile = (code, base = root) => join(base, 'src', 'data', 'parallel', code + '.json')

export function writeAtomic(file, text) {
  mkdirSync(dirname(file), { recursive: true })
  const temp = file + '.tmp'
  writeFileSync(temp, text)
  renameSync(temp, file)
}

// ---------------------------------------------------------------- YAML

/** Tokens and small records read better on one line. */
export function stringifyYaml(value) {
  const doc = new Document(value)
  visit(doc, {
    Map(_key, node, path) {
      if (path.some(item => isPair(item) && (item.key?.value === 'tokens' || item.key?.value === 'senses'))) node.flow = true
    },
  })
  return doc.toString({ lineWidth: 0, defaultStringType: 'PLAIN' })
}

export const emptyEntries = code => ({ version: FILE_VERSION, language: code, vocabulary: [], grammar: [] })
export const emptyLessons = code => ({ version: FILE_VERSION, language: code, last_phrase_id: 0, lessons: [] })

/** The authored files of a language, or empty ones. */
export function readParallel(code, base = root) {
  const read = (file, empty) => existsSync(file) ? { ...empty, ...parse(readFileSync(file, 'utf8')) } : empty
  const entries = read(entriesFile(code, base), emptyEntries(code))
  const lessons = read(lessonsFile(code, base), emptyLessons(code))
  entries.vocabulary ??= []; entries.grammar ??= []; lessons.lessons ??= []
  return { entries, lessons }
}

export function parallelTexts(code, data) {
  const header = '# Generated by scripts/build-parallel-lessons.mjs. Entries here are source: parallel-authored; the imported JLPT/TOPIK files are never edited.\n'
  const entries = { ...data.entries, vocabulary: [...data.entries.vocabulary].sort(byId), grammar: [...data.entries.grammar].sort(byId) }
  const lessons = { ...data.lessons, lessons: [...data.lessons.lessons].sort((a, b) => a.number - b.number) }
  return { entries: header + stringifyYaml(entries), lessons: header + stringifyYaml(lessons) }
}
const byId = (a, b) => a.id < b.id ? -1 : a.id > b.id ? 1 : 0

export function writeParallel(code, data, base = root) {
  const texts = parallelTexts(code, data)
  writeAtomic(entriesFile(code, base), texts.entries)
  writeAtomic(lessonsFile(code, base), texts.lessons)
}

