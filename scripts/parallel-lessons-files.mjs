export const ZH_BANDS = ['1']

/**
 * The Chinese lessons the parallel lessons follow: the v2 groups of src/data/v2/hsk-N.generated.json (HSK 1: 87 groups, zh-hsk-1-lesson-0001 ...), in group order; lesson number = group number.
 * Each has the senses and grammar points it introduces (a unit already introduced by an earlier group is review and left out), its authored examples with translations, and
 * readable phrases of src/data/phrases whose words are all introduced by lessons 1..N (those of lesson N, most new words first, up to maxPhrases beyond the examples).
 */
export function loadChineseLessons({ base = root, maxPhrases = 8, bands = ZH_BANDS } = {}) {
  const data = join(base, 'src', 'data')
  const lessons = []
  const vocabularyOf = new Map(), grammarOf = new Map(), firstGroup = new Map()
  let number = 0
  const groups = []
  for (const band of bands) {
    const file = JSON.parse(readFileSync(join(data, 'v2', 'hsk-' + band + '.generated.json'), 'utf8'))
    for (const record of file.vocabulary) vocabularyOf.set(record.lb, record)
    for (const record of file.grammar ?? []) grammarOf.set(record.lb, record)
    for (const group of file.groups) groups.push({ band, group })
  }
  const seenWords = new Set(), seenGrammar = new Set()
  const text = segments => segments.map(segment => segment.word ? vocabularyOf.get(segment.word)?.ch ?? '' : segment.punctuation ?? '').join('')
  for (const { group } of groups) {
    number++
    const words = [], grammar = []
    for (const unit of group.units) {
      if (unit.kind === 'vocabulary' && !seenWords.has(unit.ref)) { seenWords.add(unit.ref); firstGroup.set(unit.ref, number); const record = vocabularyOf.get(unit.ref); if (record) words.push({ id: record.id, ch: record.ch, pr: record.pr, ds: record.ds, lb: record.lb }) }
      if (unit.kind === 'grammar' && !seenGrammar.has(unit.ref)) { seenGrammar.add(unit.ref); const record = grammarOf.get(unit.ref); if (record) grammar.push({ id: record.id, ch: record.pt, ds: record.ds, lb: record.lb }) }
    }
    const examples = []
    for (const example of group.examples ?? []) { const zh = text(example.segments); if (zh && example.translation && !examples.some(item => item.zh === zh)) examples.push({ ref: 'ex:' + example.id, zh, en: example.translation, lb: example.segments.filter(segment => segment.word).map(segment => segment.word) }) }
    lessons.push({ number, id: group.id, words, grammar, examples, phrases: [] })
  }
  // readable phrases of the phrase bank: every word introduced by lessons 1..N, assigned to the lesson that introduces the last of them
  const pool = []
  for (const band of bands) {
    const file = join(data, 'phrases', 'hsk-' + band + '.json')
    if (!existsSync(file)) continue
    for (const phrase of JSON.parse(readFileSync(file, 'utf8')).phrases) {
      const at = phrase.words.map(lb => firstGroup.get(lb))
      if (at.every(Boolean)) pool.push({ ref: band + ':' + phrase.id, zh: phrase.zh, en: phrase.en, lb: phrase.words, lesson: Math.max(...at) })
    }
  }
  const seen = new Set(lessons.flatMap(lesson => lesson.examples.map(example => example.zh)))
  for (const lesson of lessons) {
    const own = new Set(lesson.words.map(word => word.lb))
    const chosen = pool.filter(phrase => phrase.lesson === lesson.number && !seen.has(phrase.zh))
      .map(phrase => ({ phrase, fresh: new Set(phrase.lb.filter(lb => own.has(lb))).size }))
      .sort((x, y) => y.fresh - x.fresh || x.phrase.zh.length - y.phrase.zh.length || x.phrase.ref.localeCompare(y.phrase.ref))
      .slice(0, maxPhrases).map(item => item.phrase)
    for (const phrase of chosen) seen.add(phrase.zh)
    // the group's authored examples come first; the phrase source of the lesson is examples plus the chosen bank phrases
    lesson.phrases = [...lesson.examples.map(example => ({ ref: example.ref, zh: example.zh, en: example.en })), ...chosen.map(phrase => ({ ref: phrase.ref, zh: phrase.zh, en: phrase.en }))]
  }
  return { lessons, count: lessons.length }
}

// ---------------------------------------------------------------- reference entries (read only)

/** Hiragana for katakana, so a reading matches however the source wrote it. */
export const hira = text => String(text ?? '').replace(/[\u30a1-\u30f6]/g, ch => String.fromCharCode(ch.charCodeAt(0) - 0x60)).replace(/\s+/g, '')
/** What a word is matched on: Japanese form and kana reading, Korean the Hangul form (the TOPIK files carry no reading). */
export const matchKey = (code, form, reading) => code === 'ja' ? String(form).trim() + '|' + (hira(reading) || hira(form)) : String(form).trim()

export function loadReferences(code, base = root) {
  const language = languageOf(code)
  const vocabulary = new Map(), grammar = new Map(), byKey = new Map(), byForm = new Map(), byKana = new Map(), byReading = new Map()
  const push = (map, key, id) => { if (!map.has(key)) map.set(key, []); map.get(key).push(id) }
  const folder = band => join(base, 'curriculum', language.dir, (code === 'ja' ? 'jlpt-' : 'topik-') + band)
  for (const band of language.jlpt) {
    const vocabFile = join(folder(band), 'vocabulary.yaml'), grammarFile = join(folder(band), 'grammar.yaml')
    if (existsSync(vocabFile)) for (const entry of parse(readFileSync(vocabFile, 'utf8')) ?? []) {
      // JMdict marks words that are normally written in kana: they are matched on the reading alone and shown in kana
      const kanaOnly = code === 'ja' && /usually written using kana alone/i.test(entry.english ?? '')
      vocabulary.set(entry.id, { id: entry.id, target: entry.target, reading: entry.reading || '', english: entry.english, pos: entry.part_of_speech, kanaOnly })
      push(byKey, matchKey(code, entry.target, entry.reading), entry.id)
      push(byForm, String(entry.target).trim(), entry.id)
      if (kanaOnly && entry.reading) push(byKana, hira(entry.reading), entry.id)
      if (code === 'ja' && entry.reading) push(byReading, hira(entry.reading), entry.id)
    }
    if (existsSync(grammarFile)) for (const entry of parse(readFileSync(grammarFile, 'utf8')) ?? []) grammar.set(entry.id, { id: entry.id, pattern: entry.pattern, english: entry.english })
  }
  return { vocabulary, grammar, byKey, byForm, byKana, byReading }
}

/** Every entry the files know: references, then the parallel-authored ones. */
export function entryIndex(references, entries) {
  // a word that is normally written in kana is shown in kana (あなた, not 貴方)
  const vocabulary = new Map([...references.vocabulary].map(([id, entry]) => [id, entry.kanaOnly && entry.reading ? { ...entry, target: entry.reading } : entry]))
  const grammar = new Map(references.grammar)
  for (const entry of entries.vocabulary) vocabulary.set(entry.id, { id: entry.id, target: entry.target, reading: entry.reading || '', english: entry.english, pos: entry.part_of_speech, hanja: entry.hanja, isNew: true })
  for (const entry of entries.grammar) grammar.set(entry.id, { id: entry.id, pattern: entry.pattern, english: entry.english, note: entry.note, isNew: true })
  return { vocabulary, grammar }
}

// ---------------------------------------------------------------- readability

/** First lesson that teaches each word entry and each grammar point (a point is taught in the first lesson whose phrases use it). */
export function taughtLessons(lessons) {
  const words = new Map(), grammar = new Map()
  for (const lesson of lessons) {
    for (const word of lesson.words ?? []) if (word.entry && (!words.has(word.entry) || words.get(word.entry) > lesson.number)) words.set(word.entry, lesson.number)
    for (const id of [...(lesson.grammar_intro ?? []), ...(lesson.phrases ?? []).flatMap(phrase => phrase.grammar ?? [])]) if (!grammar.has(id) || grammar.get(id) > lesson.number) grammar.set(id, lesson.number)
  }
  return { words, grammar }
}

/** The lesson from which a phrase is readable: the latest first-lesson of anything it uses. Infinity when something is not taught at all. */
export function readyAtOf(phrase, taught) {
  let at = 0
  for (const id of phrase.words ?? []) at = Math.max(at, taught.words.get(id) ?? Infinity)
  for (const id of phrase.grammar ?? []) at = Math.max(at, taught.grammar.get(id) ?? Infinity)
  return at
}

/** Sets readyAt, strict and each lesson's grammar_taught from the phrases (derived data, recomputed after every change). */
export function refreshReadability(lessons) {
  const taught = taughtLessons(lessons)
  for (const lesson of lessons) {
    lesson.grammar_taught = [...new Set([...(lesson.grammar_intro ?? []), ...(lesson.phrases ?? []).flatMap(phrase => phrase.grammar ?? [])].filter(id => taught.grammar.get(id) === lesson.number))].sort()
    for (const phrase of lesson.phrases ?? []) { phrase.readyAt = readyAtOf(phrase, taught); phrase.strict = phrase.readyAt <= lesson.number }
  }
  return taught
}

/** Strict phrases per lesson, and per word entry (every phrase counts for each word it uses). */
export function strictReport(lessons, taught = taughtLessons(lessons)) {
  const perLesson = lessons.map(lesson => ({ number: lesson.number, phrases: (lesson.phrases ?? []).length, strict: (lesson.phrases ?? []).filter(phrase => phrase.strict).length }))
  const perWord = new Map()
  for (const lesson of lessons) for (const phrase of lesson.phrases ?? []) if (phrase.strict) for (const id of new Set(phrase.words ?? [])) perWord.set(id, (perWord.get(id) ?? 0) + 1)
  const noStrict = [], noEquivalent = [], seen = new Set()
  for (const lesson of lessons) for (const sense of lesson.senses ?? []) {
    if (!sense.entry && sense.grammar) continue
    if (!sense.entry) { noEquivalent.push({ lesson: lesson.number, zh: sense.zh, note: sense.note ?? '' }); continue }
    if (perWord.get(sense.entry)) continue
    const word = (lesson.words ?? []).find(item => item.entry === sense.entry)
    noStrict.push({ lesson: lesson.number, zh: sense.zh, entry: sense.entry, form: word?.form })
  }
  return { perLesson, perWord, noStrict, noEquivalent, taught }
}

// ---------------------------------------------------------------- writing coverage

const isKanji = ch => /\p{Script=Han}/u.test(ch)
const isKana = ch => /[\p{Script=Hiragana}\p{Script=Katakana}ー]/u.test(ch)
const isHangul = ch => /[\u1100-\u11ff\u3130-\u318f\uac00-\ud7a3]/u.test(ch)

/** The characters a language's lesson data writes (words, readings of kept entries, phrase texts) that the writing data should cover. */
export function usedCharacters(code, lessons, index) {
  const wanted = code === 'ja' ? ch => isKanji(ch) || isKana(ch) : isHangul
  const used = new Set()
  const add = text => { for (const ch of String(text ?? '')) if (wanted(ch)) used.add(ch) }
  for (const lesson of lessons) {
    for (const word of lesson.words ?? []) if (word.entry) { add(word.form); add(word.reading) }
    for (const phrase of lesson.phrases ?? []) { add(phrase.text); add(phrase.reading) }
  }
  for (const entry of index?.vocabulary?.values?.() ?? []) if (entry.isNew) { add(entry.target); add(entry.reading) }
  return used
}

export function readStrokeIndex(code, base = root) {
  const file = join(base, 'public', 'characters', languageOf(code).dir, 'index.generated.json')
  return existsSync(file) ? new Set(Object.keys(JSON.parse(readFileSync(file, 'utf8')).characters)) : new Set()
}

export function writingCoverage(code, lessons, index, strokes = readStrokeIndex(code)) {
  const used = usedCharacters(code, lessons, index)
  const missing = [...used].filter(ch => !strokes.has(ch)).sort((a, b) => a.codePointAt(0) - b.codePointAt(0))
  return { used: used.size, covered: used.size - missing.length, missing }
}

// ---------------------------------------------------------------- app JSON

/**
 * Word forms of the phrases (src/core/forms): every inflected token gets the form that builds its surface, irregular forms become lesson-scoped items,
 * and a phrase is readable only once the grammar point of each of its forms is taught. Returns what the app JSON adds, and the phrases that stopped being strict.
 */
export function analyseForms(code, lessons, taught, data, references, base = root) {
  const engine = createForms(loadFormsRules(code, base))
  const vocabulary = rawVocabulary(references, data.entries)
  const classes = classifyEntries(engine, vocabulary, loadClassOverrides(code, base))
  const result = analysePhrases(engine, lessons, vocabulary, classes)
  const items = {}, tags = new Map(), phraseItems = new Map()
  for (const tag of result.tagged) {
    tags.set(tag.lesson + ':' + tag.phrase + ':' + tag.token, tag)
    if (!tag.item) continue
    const key = tag.lesson + ':' + tag.phrase
    if (!phraseItems.has(key)) phraseItems.set(key, new Set())
    phraseItems.get(key).add(tag.item)
    if (!items[tag.item] || items[tag.item].lesson > tag.lesson) {
      const made = engine.forms(tag.formLemma, tag.formClass, tag.form, code === 'ja' && tag.formReading ? { reading: tag.formReading } : {})
      items[tag.item] = { lemma: tag.formLemma, form: tag.form, class: tag.formClass, entry: tag.id, surface: made.surface, ...(made.reading ? { reading: made.reading } : {}), lesson: tag.lesson }
    }
  }
  const lostStrict = []
  for (const lesson of lessons) for (const phrase of lesson.phrases ?? []) {
    let ready = phrase.readyAt, reason = null
    for (const [key, tag] of tags) {
      if (!key.startsWith(lesson.number + ':' + phrase.id + ':')) continue
      const need = tag.grammar ? taught.grammar.get(tag.grammar) ?? Infinity : 0
      if (need > ready) { ready = need; reason = { grammar: tag.grammar, form: tag.form, lemma: tag.formLemma, taughtAt: need } }
      if (tag.item) ready = Math.max(ready, items[tag.item].lesson)
    }
    if (ready !== phrase.readyAt) {
      const was = phrase.strict
      phrase.readyAt = ready; phrase.strict = ready <= lesson.number
      if (was && !phrase.strict) lostStrict.push({ lesson: lesson.number, phrase: phrase.id, text: phrase.text, ...reason })
    }
  }
  return { classes, items, tags, phraseItems, lostStrict, counts: { tagged: result.tagged.length, ambiguous: result.ambiguous.length, unmatched: result.unmatched.length, nominal: result.nominal, bare: result.bare, head: result.head, items: Object.keys(items).length, lostStrict: lostStrict.length }, result }
}

/** src/data/parallel/<language>.json: the lessons with the entries they use, ready for the app (no reference file is read at run time). */
export function buildAppJson(code, data, references, base = root) {
  const lessons = [...data.lessons.lessons].sort((a, b) => a.number - b.number)
  const taught = refreshReadability(lessons)
  const forms = analyseForms(code, lessons, taught, data, references, base)
  const index = entryIndex(references, data.entries)
  const usedWords = new Set(), usedGrammar = new Set()
  for (const lesson of lessons) {
    for (const word of lesson.words ?? []) if (word.entry) usedWords.add(word.entry)
    for (const phrase of lesson.phrases ?? []) { (phrase.words ?? []).forEach(id => usedWords.add(id)); (phrase.grammar ?? []).forEach(id => usedGrammar.add(id)) }
  }
  const entries = {}, grammar = {}
  for (const id of [...usedWords].sort()) {
    const entry = index.vocabulary.get(id)
    if (!entry) throw new Error('A lesson uses the word entry ' + id + ' that no file defines.')
    const cls = forms.classes.get(id)?.class
    entries[id] = { target: entry.target, ...(entry.reading ? { reading: entry.reading } : {}), english: entry.english, ...(entry.pos ? { pos: entry.pos } : {}), ...(entry.hanja ? { hanja: entry.hanja } : {}), ...(cls ? { class: cls } : {}), ...(entry.isNew ? { new: true } : {}) }
  }
  for (const id of [...usedGrammar].sort()) {
    const entry = index.grammar.get(id)
    if (!entry) throw new Error('A lesson uses the grammar entry ' + id + ' that no file defines.')
    grammar[id] = { pattern: entry.pattern, english: entry.english, ...(entry.isNew ? { new: true } : {}) }
  }
  const tokensOf = (lesson, phrase) => phrase.tokens.map((token, at) => {
    const tag = forms.tags.get(lesson.number + ':' + phrase.id + ':' + at)
    return tag ? { ...token, form: tag.form, ...(tag.span ? { span: tag.span } : {}) } : token
  })
  const out = lessons.map(lesson => ({
    lesson: lesson.id, number: lesson.number,
    words: (lesson.words ?? []).map(word => ({ entry: word.entry, status: word.status, zh: word.zh ?? [], ...(word.extra ? { extra: true } : {}), ...(word.new ? { new: true } : {}) })),
    senses: (lesson.senses ?? []).map(sense => ({ zh: sense.zh, status: sense.status, entry: sense.entry ?? null, ...(sense.grammar ? { grammar: sense.grammar } : {}), ...(sense.note ? { note: sense.note } : {}) })),
    grammar: lesson.grammar_taught ?? [],
    ...(Object.entries(forms.items).some(([, item]) => item.lesson === lesson.number) ? { forms: Object.entries(forms.items).filter(([, item]) => item.lesson === lesson.number).map(([id]) => id).sort() } : {}),
    phrases: (lesson.phrases ?? []).map(phrase => ({ id: phrase.id, text: phrase.text, ...(phrase.reading ? { reading: phrase.reading } : {}), en: phrase.en, ...(phrase.zh ? { zh: phrase.zh } : {}), tokens: tokensOf(lesson, phrase), words: phrase.words, grammar: phrase.grammar ?? [], ...(forms.phraseItems.has(lesson.number + ':' + phrase.id) ? { forms: [...forms.phraseItems.get(lesson.number + ':' + phrase.id)].sort() } : {}), strict: phrase.strict === true })),
  }))
  const phrases = out.reduce((sum, lesson) => sum + lesson.phrases.length, 0)
  const strict = out.reduce((sum, lesson) => sum + lesson.phrases.filter(phrase => phrase.strict).length, 0)
  const formItems = Object.fromEntries(Object.entries(forms.items).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0))
  return { schemaVersion: 1, language: code, counts: { lessons: out.length, words: usedWords.size, grammar: usedGrammar.size, phrases, strict, forms: forms.counts }, entries, grammar, formItems, lessons: out }
}

export const appJsonText = (code, data, references, base = root) => JSON.stringify(buildAppJson(code, data, references, base)) + '\n'
